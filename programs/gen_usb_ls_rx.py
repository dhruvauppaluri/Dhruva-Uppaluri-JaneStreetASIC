#!/usr/bin/env python3
"""Generate programs/usb_ls_rx.setl: a USB low-speed packet receiver with
clock recovery, NRZI decoding, bit un-stuffing and CRC-16 checking on chip.

Clock recovery: after each mid-bit sample the lane waits for "edge or timeout".
An edge (a bit boundary) re-centres the next sample half a bit later. A
timeout means no transition, and the sample is taken where mid-bit should be.
Stuffing guarantees a transition at least every 7 bits, so the sample point never drifts.

NRZI: the line level before each bit is encoded in which copy of the states
the lane is in (J or K).  The decoded bit is shifted in from the constant
inputs `one` / `zero`, so the CRC unit and the ones counter (CTRL_CRC_IN) see
decoded bits.  After six 1s the next bit is a stuff bit and is skipped.

Every byte (SYNC 0x80, PID, data, CRC) goes to RX.  At EOP (SE0) after a data
packet the CRC residue is checked; a mismatch raises the lane's host event.

Lane setup: CTRL = CTRL_CRC | CTRL_CRC_IN | (6 << 4); CRC poly 0xA001, init
0xFFFF, residue 0xB001 (USB CRC-16 residual, reflected); TA = 15 (no edge:
W 16 + S + M/N + B + C = 20 ticks per bit), TB = 8 (edge to sample); same
tick rate as the transmitter (20 ticks per bit).

The lane flag marks "data bytes received"; the program reads it as flag<LANE>.

Usage: gen_usb_ls_rx.py [DP_PIN DM_PIN [LANE [OUT]]]  (default uo0 uo1 1: loopback on lane 1)
"""
import os
import sys

FAM = ["Y", "Z", "D"]     # SYNC, PID, data(+CRC) bytes
OPP = {"J": "K", "K": "J"}
lines = []


def st(label, body, target=""):
    lines.append(f"{label + ':':12s} {body:40s} {target}".rstrip())


def family(f, x):
    o = OPP[x]
    # wait for the bit boundary (edge) or the expected mid-bit (timeout)
    st(f"W{f}{x}", "in dp timer=TA wait edge_or_timer", f"if timer goto S{f}{x} else R{f}{x}")
    st(f"R{f}{x}", "timer=TB wait timer", f"goto S{f}{x}")
    # sample D+; when it reads low, D- tells J from SE0.  Every path from the
    # sample to the shift has exactly one state in between (M or N), so all bits
    # take the same number of ticks and the sample point does not drift.
    if x == "J":    # D+ low expected
        st(f"S{f}{x}", "in dp", f"if pin goto N{f}{x} else M{f}{x}")
        st(f"N{f}{x}", "", f"goto B0{f}K")
        st(f"M{f}{x}", "in dm", f"if pin goto B1{f}J else E{f}")
    else:           # D+ high expected
        st(f"S{f}{x}", "in dp", f"if pin goto N{f}{x} else M{f}{x}")
        st(f"N{f}{x}", "", f"goto B1{f}K")
        st(f"M{f}{x}", "in dm", f"if pin goto B0{f}J else E{f}")
    # decoded bits: 1 = no transition (line stays x), 0 = transition (line now x)
    st(f"B1{f}{x}", "in one shift dec", f"if ones goto U{f}{x} else C{f}{x}")
    st(f"B0{f}{x}", "in zero shift dec", f"goto C{f}{x}")
    st(f"C{f}{x}", "", f"if cnt0 goto Y{f}{x} else W{f}{x}")
    # stuff bit: wait for it, expect the transition, do not shift
    st(f"U{f}{x}", "ones clr", f"goto KW{f}{x}")
    st(f"KW{f}{x}", "in dp timer=TA wait edge_or_timer", f"if timer goto KS{f}{x} else KR{f}{x}")
    st(f"KR{f}{x}", "timer=TB wait timer", f"goto KS{f}{x}")
    st(f"KS{f}{x}", "", f"goto C{f}{o}")
    # byte complete
    nxt = {"Y": "Z", "Z": "D", "D": "D"}[f]
    st(f"Y{f}{x}", "push flag set" if f == "D" else "push", f"goto P{f}{x}")
    if f == "Z":                      # PID received: the CRC covers what follows
        st(f"P{f}{x}", "crc clr", f"goto Q{f}{x}")
        st(f"Q{f}{x}", "cnt=8", f"goto W{nxt}{x}")
    else:
        st(f"P{f}{x}", "cnt=8", f"goto W{nxt}{x}")


LANE = 1


def main(dp="uo0", dm="uo1", lane="1", out=None):
    global LANE
    LANE = int(lane)
    lines.append("; GENERATED by programs/gen_usb_ls_rx.py -- edit the generator, not this file.")
    for doc in __doc__.strip().splitlines():
        lines.append(f"; {doc}".rstrip())
    lines.append(f".pin dp {dp}")
    lines.append(f".pin dm {dm}")
    lines.append(".lane usb_ls_rx")
    st("U_IDLE", "ones clr flag clr", "goto U_I2")
    st("U_I2", "cnt=8 in dp wait rise", "goto RYJ")       # J -> K: start of SYNC
    for f in FAM:
        for x in "JK":
            family(f, x)
    for f in FAM:                    # SE0: end of packet
        if f == "D":       # check the CRC only if data/CRC bytes arrived (not handshakes)
            st(f"E{f}", f"in flag{LANE}", "if pin goto EC else EW")
            st("EC", "", "if crcok goto EW else EBAD")
        else:
            st(f"E{f}", "", "goto EW")
    st("EBAD", "event", "goto EW")
    st("EW", "in dm wait pin", "goto U_IDLE")            # back to J
    out = out or os.path.join(os.path.dirname(os.path.abspath(__file__)), "usb_ls_rx.setl")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    print(main(*sys.argv[1:]))
