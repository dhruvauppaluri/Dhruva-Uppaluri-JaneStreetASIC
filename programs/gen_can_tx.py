#!/usr/bin/env python3
"""Generate programs/can_tx.setl: a CAN 2.0A data-frame transmitter.

The chip does the bit-level work: stuffing after five identical bits, CRC-15
(MSB first: poly 0x4599 left-aligned as 0x8B32 in the 16-bit unit, init 0), the
CRC delimiter, reading the ACK slot, and the end of frame.

Host side: push 3 header bytes, then DLC data bytes; keep the FIFO fed.  The
header is 5 zero pad bits followed by SOF(0), ID[10:0], RTR, IDE(0), r0(0),
DLC[3:0], MSB first (setl.can.header()).  The pad bits are shifted out
silently before SOF; the CRC starts at 0, so zero bits do not change it.
A missing ACK raises the lane's host event.

Lane setup: CTRL = CTRL_MSB | CTRL_CRC | CTRL_CRC_LEFT | CTRL_RUN_ANY | (5 << 4);
CRC poly 0x8B32, init 0.  TA = BIT - 5, TB = BIT - 4 (BIT = ticks per bit),
TB is also used for the tail.  slot 0 = TXD (recessive 1); RXD on `rx`.
"""
import os
import sys

lines = []


def st(label, body, target=""):
    lines.append(f"{label + ':':10s} {body:44s} {target}".rstrip())


def family(f, end):
    st(f"S{f}", "out 0 shift dec timer=TA wait timer", f"goto D1{f}")
    st(f"D1{f}", "", f"if ones goto V1{f} else D2{f}")
    # stuff bit: the opposite of the bus level just sent, on the next bit edge
    st(f"V1{f}", "", f"goto V2{f}")
    st(f"V2{f}", "", f"goto V3{f}")
    st(f"V3{f}", "in txd", f"if pin goto T0{f} else T1{f}")
    st(f"T0{f}", "set 0=0 ones clr timer=TB wait timer", f"goto D2{f}")
    st(f"T1{f}", "set 0=1 ones clr timer=TB wait timer", f"goto D2{f}")
    st(f"D2{f}", "", f"if cnt0 goto B1{f} else P1{f}")
    st(f"P1{f}", "", f"goto P2{f}")
    st(f"P2{f}", "", f"goto S{f}")
    for line in end:
        st(*line)


def main(rx="ui0", out=None):
    lines.append("; GENERATED by programs/gen_can_tx.py -- edit the generator, not this file.")
    for doc in __doc__.strip().splitlines():
        lines.append(f"; {doc}".rstrip())
    lines.append(f".pin rx {rx}")
    lines.append(".pin txd uo0")
    lines.append(".lane can_tx")
    st("C_IDLE", "set 0=1 crc clr wait txready", "goto C_P0")
    st("C_P0", "pop cnt=3", "goto C_P1")                    # first header byte
    for k in range(1, 6):                                    # 5 silent pad bits
        st(f"C_P{k}", "shift", f"goto C_P{k + 1}")
    st("C_P6", "ones clr", "goto SH0")                       # bus idle: no run yet
    family("H0", [("B1H0", "cnt=8", "goto B2H0"), ("B2H0", "pop", "goto SH1")])
    family("H1", [("B1H1", "cnt=8", "goto B2H1"), ("B2H1", "pop", "goto SH2")])
    family("H2", [("B1H2", "cnt=8", "if txready goto B2H2 else B3H2"),
                  ("B2H2", "pop", "goto SD"),
                  ("B3H2", "crc hi", "goto SC1")])             # DLC 0
    family("D", [("B1D", "cnt=8", "if txready goto B2D else B3D"),
                 ("B2D", "pop", "goto SD"),
                 ("B3D", "crc hi", "goto SC1")])
    # CRC-15 sits in bits 15..1: send 8 then 7 bits, re-reading the top byte
    family("C1", [("B1C1", "cnt=7", "goto B2C1"), ("B2C1", "crc hi", "goto SC2")])
    family("C2", [("B1C2", "", "goto B2C2"), ("B2C2", "", "goto K_DEL")])
    # tail: CRC delimiter, ACK slot (sampled mid-bit), ACK delimiter, EOF + IFS
    st("K_DEL", "set 0=1 timer=TB wait timer", "goto K_A1")
    st("K_A1", "timer=TA wait timer", "goto K_A2")          # to mid ACK slot
    st("K_A2", "in rx", "if pin goto K_NAK else K_A3")
    st("K_NAK", "event", "goto K_A3")
    st("K_A3", "cnt=11", "goto K_EOF")                       # rest of ACK, delimiter, EOF, IFS
    st("K_EOF", "dec timer=TB wait timer", "if cnt0 goto C_IDLE else K_EOF2")
    st("K_EOF2", "", "goto K_EOF")
    out = out or os.path.join(os.path.dirname(os.path.abspath(__file__)), "can_tx.setl")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    print(main(*sys.argv[1:]))
