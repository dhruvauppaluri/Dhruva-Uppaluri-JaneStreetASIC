#!/usr/bin/env python3
"""Generate programs/usb_ls_tx.setl: a USB low-speed packet transmitter.

The chip does all the line work: SYNC, NRZI, bit stuffing (from the `ones`
condition), CRC-16 over the data field sent complemented (`crc nlo/nhi`), and EOP.

Every bit, including stuffed bits and byte boundaries, takes exactly
20 ticks (666.7 ns at 60 MHz in 2-lane mode): each bit is an entry state of
TA+1 = 14 ticks plus six one-tick decision states, and every path through the
decisions has the same length.  The line state (J or K) and the packet phase
are encoded in which copy of the bit states the lane is in, so the program is
5 phases x 2 line states of the same small bit machine (181 records).

Lane setup: CTRL = CTRL_CRC | (6 << 4) (stuff after six 1s, counted on the sent
bits); CRC poly 0xA001, init 0xFFFF; TA = 13, TB = 14; slots 0 = D+, 1 = D-.
The host pushes PID, then the data bytes, and keeps the FIFO fed; set HFLAG for
a handshake packet (PID only, no CRC).
"""
import os

PHASES = ["Y", "Z", "D", "L", "H"]   # SYNC, PID, data, CRC low, CRC high
LINE = {"J": "set 0=0 1=1", "K": "set 0=1 1=0"}   # low speed: J = D- high
OTHER = {"J": "K", "K": "J"}
lines = []


def st(label, body, target=""):
    lines.append(f"{label + ':':12s} {body:44s} {target}".rstrip())


def bit_machine(f, x):
    o = OTHER[x]
    st(f"S{f}{x}", f"{LINE[x]} shift dec timer=TA wait timer", f"goto D1{f}{x}")
    st(f"T{f}{x}", f"{LINE[x]} ones clr timer=TB wait timer", f"goto D2{f}{x}")
    st(f"D1{f}{x}", "", f"if ones goto V1{f}{x} else D2{f}{x}")
    # a stuff bit starts on the same bit edge as a normal bit would: after D1 a
    # normal bit spends 5 ticks (D2, P1-P3, D3), so the stuff path pads 5
    for k in range(1, 5):
        st(f"V{k}{f}{x}", "", f"goto V{k + 1}{f}{x}")
    st(f"V5{f}{x}", "", f"goto T{f}{o}")
    st(f"D2{f}{x}", "", f"if cnt0 goto B1{f}{x} else P1{f}{x}")
    st(f"P1{f}{x}", "", f"goto P2{f}{x}")
    st(f"P2{f}{x}", "", f"goto P3{f}{x}")
    st(f"P3{f}{x}", "", f"goto D3{f}{x}")
    st(f"D3{f}{x}", "", f"if bit goto S{f}{x} else S{f}{o}")


def byte_end(f, x):
    # three ticks, like P1..P3, ending in a D3 of the next phase
    if f == "Y":     # SYNC sent: load the PID
        st(f"B1Y{x}", "cnt=8", f"goto B2Y{x}")
        st(f"B2Y{x}", "pop", f"goto B3Y{x}")
        st(f"B3Y{x}", "", f"goto D3Z{x}")
    elif f == "Z":   # PID sent: handshake -> EOP, else start the CRC and the data
        st(f"B1Z{x}", "cnt=8", f"if hflag goto Q2{x} else B2Z{x}")
        st(f"Q2{x}", "", f"goto Q3{x}")                     # handshake: pad to the bit edge
        st(f"Q3{x}", "", f"goto Q4{x}")
        st(f"Q4{x}", "", f"goto E1{x}")
        st(f"B2Z{x}", "crc clr", f"if txready goto B3Z{x} else B3C{x}")
        st(f"B3Z{x}", "pop", f"goto D3D{x}")
        st(f"B3C{x}", "crc nlo", f"goto D3L{x}")          # empty data field
    elif f == "D":   # data byte sent: next byte, or the CRC
        st(f"B1D{x}", "cnt=8", f"if txready goto B2D{x} else B2E{x}")
        st(f"B2D{x}", "pop", f"goto B3D{x}")
        st(f"B3D{x}", "", f"goto D3D{x}")
        st(f"B2E{x}", "crc nlo", f"goto B3E{x}")
        st(f"B3E{x}", "", f"goto D3L{x}")
    elif f == "L":   # CRC low byte sent: CRC high byte
        st(f"B1L{x}", "cnt=8", f"goto B2L{x}")
        st(f"B2L{x}", "crc nhi", f"goto B3L{x}")
        st(f"B3L{x}", "", f"goto D3H{x}")
    else:            # CRC high byte sent: end of packet
        st(f"B1H{x}", "", f"goto B2H{x}")                   # pad to the bit edge
        st(f"B2H{x}", "", f"goto B3H{x}")
        st(f"B3H{x}", "", f"goto B4H{x}")
        st(f"B4H{x}", "", f"goto E1{x}")


def main():
    lines.append("; GENERATED by programs/gen_usb_ls_tx.py -- edit the generator, not this file.")
    for doc in __doc__.strip().splitlines():
        lines.append(f"; {doc}".rstrip())
    lines.append(".lane usb_ls_tx")
    st("U_IDLE", "set 0=0 1=1 wait txready", "goto U_ST1")
    st("U_ST1", "cnt=8", "goto U_ST2")
    st("U_ST2", "ld 0x80", "goto D3YJ")                  # SYNC = 0000_0001, LSB first
    for f in PHASES:
        for x in "JK":
            bit_machine(f, x)
            byte_end(f, x)
    for x in "JK":                                         # EOP: 2 bits SE0, 1 bit J
        st(f"E1{x}", "set 0=0 1=0 timer=39 wait timer", f"goto E2{x}")
        st(f"E2{x}", "set 0=0 1=1 timer=19 wait timer", "goto U_IDLE")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "usb_ls_tx.setl")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    print(main())
